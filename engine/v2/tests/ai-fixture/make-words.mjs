// Makes the word table of src/ai-words.mjs from the Unicode 16.0 files (A5.2): letters and numbers (DerivedGeneralCategory.txt,
// gc L* and N*), spaces (gc Zs) and their word-break class (WordBreakProperty.txt). Run once, by hand, with local copies:
//   node engine/v2/tests/ai-fixture/make-words.mjs <DerivedGeneralCategory.txt> <WordBreakProperty.txt>
// It prints the module to standard output. No network: download the two files yourself from unicode.org/Public/16.0.0/ucd/.
import fs from 'node:fs';

const [gcFile, wbFile] = process.argv.slice(2);
if (!gcFile || !wbFile) { console.error('usage: make-words.mjs <DerivedGeneralCategory.txt> <WordBreakProperty.txt>'); process.exit(2); }
const rows = (file) => fs.readFileSync(file, 'utf8').split('\n').map(l => l.replace(/#.*/, '').trim()).filter(Boolean).map(l => {
  const [r, v] = l.split(';').map(s => s.trim());
  const [a, b] = r.split('..').map(h => parseInt(h, 16));
  return [a, b ?? a, v];
});
const cls = new Map();
// Word-break classes kept by the matcher: A joins with A (ALetter, Hebrew_Letter, Numeric: WB5, WB8 to WB10), K with K
// (Katakana, WB13), E (ExtendNumLet) joins with A, K and E (WB13a, WB13b), X attaches to the character before it (Extend,
// Format, WB4); every other letter or number (O: Han, Hiragana, Thai, ...) is a word of its own.
const WB = { ALetter: 'A', Hebrew_Letter: 'A', Numeric: 'A', Katakana: 'K', ExtendNumLet: 'E', Extend: 'X', Format: 'X', ZWJ: 'X' };
const wb = new Map();
for (const [a, b, v] of rows(wbFile)) for (let c = a; c <= b; c++) wb.set(c, WB[v] || 'O');
for (const [a, b, v] of rows(gcFile)) {
  if (!/^[LN]/.test(v) && v !== 'Zs') continue;
  for (let c = a; c <= b; c++) cls.set(c, v === 'Zs' ? 'S' : (wb.get(c) || 'O'));
}
// Runs of one class, written as base-36 "gap,length,class" from the end of the previous run.
const cps = [...cls.keys()].sort((x, y) => x - y);
const runs = [];
for (const c of cps) {
  const last = runs[runs.length - 1];
  if (last && last[1] === c - 1 && last[2] === cls.get(c)) last[1] = c; else runs.push([c, c, cls.get(c)]);
}
let prev = -1;
const parts = runs.map(([a, b, k]) => { const s = `${(a - prev - 1).toString(36)}.${(b - a).toString(36)}${k}`; prev = b; return s; });
const lines = [];
for (let i = 0; i < parts.length; i += 40) lines.push(`  '${parts.slice(i, i + 40).join(' ')}'`);
process.stdout.write(`// Generated by engine/v2/tests/ai-fixture/make-words.mjs from Unicode 16.0 (DerivedGeneralCategory.txt and
// WordBreakProperty.txt). Do not edit. The matcher of A5.2 uses it, never the host's Intl.
// Each entry is "<gap>.<length><class>" in base 36: the run starts gap code points after the previous run's end and
// covers length + 1 code points. Classes: S space (gc Zs); A, K, E, X, O letters and numbers by word-break class.
export const UNICODE_VERSION = '16.0.0';
export const RUNS = [
${lines.join(',\n')},
].join(' ');
`);
console.error(`${runs.length} runs`);
