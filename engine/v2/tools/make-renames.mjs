// Writes spec/2.0/renames.json, the one rename list, from its two tables: the rename table of the upgrade tool
// (reference/a13-migration.md, A13.4: hsvg/0.1 and older drafts) and the renamed words of 2.0 (11-vocabulary.md, 11.5).
// The fast tests fail while the file is stale.
// Usage: node engine/v2/tools/make-renames.mjs [--check]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const spec = path.resolve(here, '..', '..', '..', 'spec', '2.0');
export const target = path.join(spec, 'renames.json');

const GROUPS = { A: 'hsvg/0.1 documents', B: 'SVG 1.x drawings', C: 'sidecars and the ad catalog', D: 'interaction chapters',
  P: 'packages and other containers', W: 'earlier words', K: 'error codes', R: 'earlier 2.0 drafts (11.5)' };
const TREATMENT = { M: 'mechanical', R: 'review', N: 'none', D: 'dropped' };

// The cells of one table row, split on the bars outside backticks.
function cells(line) {
  const out = []; let cur = ''; let code = false;
  for (const ch of line.trim().slice(1, -1)) {
    if (ch === '`') code = !code;
    if (ch === '|' && !code) { out.push(cur.trim()); cur = ''; } else cur += ch;
  }
  out.push(cur.trim());
  return out;
}

// The rows of A13.4 (groups A to K), in table order.
function a13Rows(text) {
  const rows = []; let group = null; let inside = false;
  for (const line of text.split(/\r?\n/)) {
    if (/^## A13\.4 /.test(line)) { inside = true; continue; }
    if (inside && /^## /.test(line)) break;
    if (!inside) continue;
    const h = line.match(/^### ([A-Z])\. /); if (h) { group = h[1]; continue; }
    if (!group || !/^\| [A-Z]-\d\d /.test(line)) continue;
    const [row, from, to, last] = cells(line);
    const r = { row, group: GROUPS[row[0]], from, to, treatment: TREATMENT[last[0]] || 'per-row' };
    if (last.length > 1) r.treatmentNote = last;
    rows.push(r);
  }
  return rows;
}

// The rows of 11.5, in table order.
function vocabularyRows(text) {
  const rows = []; let inside = false;
  for (const line of text.split(/\r?\n/)) {
    if (/^## 11\.5 /.test(line)) { inside = true; continue; }
    if (inside && /^## /.test(line)) break;
    if (!inside || !/^\| R-\d\d /.test(line)) continue;
    const [row, from, to, where] = cells(line);
    rows.push({ row, group: GROUPS.R, from, to, where });
  }
  return rows;
}

export function renamesJson() {
  const read = (...p) => fs.readFileSync(path.join(spec, ...p), 'utf8');
  const rows = [...a13Rows(read('reference', 'a13-migration.md')), ...vocabularyRows(read('11-vocabulary.md'))];
  const about = 'HyperSVG 2.0, the one rename list: words, keys, marks and error codes. Rows A to K are the rename table of the upgrade tool (reference/a13-migration.md, A13.4); rows R are the words renamed while 2.0 was drafted (11-vocabulary.md, 11.5). Generated by engine/v2/tools/make-renames.mjs; do not edit.';
  return JSON.stringify({ about, rows }, null, 1) + '\n';
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = renamesJson();
  const old = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (process.argv.includes('--check')) {
    console.log(old === text ? 'renames.json is up to date' : 'renames.json is stale: run node engine/v2/tools/make-renames.mjs');
    process.exit(old === text ? 0 : 1);
  }
  fs.writeFileSync(target, text);
  console.log(`${JSON.parse(text).rows.length} rows written to spec/2.0/renames.json`);
}
