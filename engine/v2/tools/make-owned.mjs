// Writes the generated part of engine/v2/src/capabilities.mjs from spec/2.0/capabilities.json (10.11): the block
// fields and effect kinds that only a capability gives meaning to, for the capabilities this engine builds as modules
// (one file each in src/capabilities/). The core refuses such a field when its capability is not installed, because
// the absent module cannot say so itself. The fast tests fail while the part is stale.
// Usage: node engine/v2/tools/make-owned.mjs [--check]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '..', '..', '..');
export const target = path.join(repo, 'engine', 'v2', 'src', 'capabilities.mjs');
const BEGIN = '// ---- generated by engine/v2/tools/make-owned.mjs from spec/2.0/capabilities.json; do not edit ----';
const END = '// ---- end of the generated part ----';

// The capabilities with a module in this engine: src/capabilities/<id>.mjs.
export function builtModules() {
  return fs.readdirSync(path.join(repo, 'engine', 'v2', 'src', 'capabilities')).filter(f => f.endsWith('.mjs') && f !== 'all.mjs').map(f => f.slice(0, -4)).sort();
}

// The generated part. A block field counts when the registry names it plainly (a top-level key, no `.` or `[`), as a
// binding key (bindings[].<key>) of an engine capability, and the content types it owns (contentTypes)
// (its code is the engine's, so nothing else can draw or read it; a privileged capability's binding, such as media's
// video, shows nothing without its page part, A2.1); a field with another path or condition
// (addons.seats.seats[kind=character]) is the checker's to prove.
export function ownedPart() {
  const reg = JSON.parse(fs.readFileSync(path.join(repo, 'spec', '2.0', 'capabilities.json'), 'utf8'));
  const built = new Set(builtModules());
  const fields = {}; const kinds = {}; const bindings = {}; const contentTypes = {}; const humanOnly = {}; const textKeys = {}; const textInputs = {};
  const manifest = (c) => { const f = c.manifest && path.join(repo, 'spec', '2.0', ...c.manifest.split('/')); return f && fs.existsSync(f) ? JSON.parse(fs.readFileSync(f, 'utf8')) : null; };
  for (const c of reg.capabilities) {
    if (!built.has(c.name)) continue;
    for (const f of c.owns?.blockFields || []) {
      if (/^[A-Za-z][A-Za-z0-9]*$/.test(f)) fields[f] = c.name;
      const b = c.contract === 'engine' && /^bindings\[\]\.([A-Za-z][A-Za-z0-9]*)$/.exec(f); if (b) bindings[b[1]] = c.name;
    }
    if (c.contract === 'engine') for (const t of c.contentTypes || []) contentTypes[t] = c.name;
    for (const k of c.owns?.effectKinds || []) kinds[k] = c.name;
    // Door 2: a built-in's binding key (grammar.draws.<name>) and content types (grammar.contentTypes) are its own; a call
    // marked humanOnly needs a person's press.
    const g = manifest(c)?.grammar || {};
    for (const k of Object.keys(g.draws || {})) { bindings[k] = c.name; if (g.draws[k]?.text === true) textKeys[k] = c.name; }
    for (const t of Object.keys(g.contentTypes || {})) contentTypes[t] = c.name;
    for (const [v, call] of Object.entries(g.calls || {})) if (call?.humanOnly === true) humanOnly[`${c.name}.${v}`] = c.name;
    // A call's input the manifest types as a string is a text slot (D31.1): plain words, or {{ }} for a formula.
    for (const [v, call] of Object.entries(g.calls || {})) {
      const ks = Object.entries(call?.with?.properties || {}).filter(([, d]) => d?.type === 'string').map(([k]) => k).sort();
      if (ks.length) textInputs[`${c.name}.${v}`] = ks;
    }
  }
  const obj = (o) => (!Object.keys(o).length ? '{}' : `{ ${Object.entries(o).sort(([a], [b]) => (a < b ? -1 : 1)).map(([k, v]) => `${/^[A-Za-z_]\w*$/.test(k) ? k : JSON.stringify(k)}: '${v}'`).join(', ')} }`);
  const lists = (o) => (!Object.keys(o).length ? '{}' : `{ ${Object.entries(o).sort(([a], [b]) => (a < b ? -1 : 1)).map(([k, v]) => `${JSON.stringify(k)}: [${v.map(x => `'${x}'`).join(', ')}]`).join(', ')} }`);
  return `${BEGIN}
// Block fields owned by a capability built as a module here, effect kinds (the block field effects), binding keys
// and content types of inputs, by owner.
export const OWNED_FIELDS = Object.freeze(${obj(fields)});
export const OWNED_EFFECT_KINDS = Object.freeze(${obj(kinds)});
export const OWNED_BINDING_KEYS = Object.freeze(${obj(bindings)});
export const OWNED_CONTENT_TYPES = Object.freeze(${obj(contentTypes)});
// Calls a built-in's manifest marks humanOnly (door 2): only a person's press may cause them (10.5).
export const HUMAN_ONLY_CALLS = Object.freeze(${obj(humanOnly)});
// Binding keys whose add-on paints text in the target (draws text: true): the drawing paints them as rich text, and
// a label names the part as for text.
export const TEXT_BINDING_KEYS = Object.freeze(${obj(textKeys)});
// Call inputs a built-in's manifest types as a string: text slots (D31.1), by call.
export const TEXT_CALL_INPUTS = Object.freeze(${lists(textInputs)});
${END}`;
}

// The file with its generated part replaced.
export function ownedFile(text) {
  const a = text.indexOf(BEGIN); const b = text.indexOf(END);
  if (a < 0 || b < a) throw new Error(`${target} has no generated part (${BEGIN})`);
  return text.slice(0, a) + ownedPart() + text.slice(b + END.length);
}

// The core release (D30) holds no built-in add-on's module or manifest, so the part cannot be made again there: it is
// kept as the authors' repository made it, and the add-ons release checks it.
export const addonsHeld = () => builtModules().length > 0;

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (!addonsHeld()) {
    console.log('capabilities.mjs is kept: this release holds no built-in add-on (D30); the hypersvg-addons release checks its generated part');
    process.exit(0);
  }
  const old = fs.readFileSync(target, 'utf8');
  const text = ownedFile(old);
  if (process.argv.includes('--check')) { console.log(old === text ? 'capabilities.mjs is up to date' : 'capabilities.mjs is stale: run engine/v2/tools/make-owned.mjs'); process.exit(old === text ? 0 : 1); }
  if (old !== text) fs.writeFileSync(target, text);
  console.log(old === text ? 'capabilities.mjs is up to date' : 'wrote the generated part of engine/v2/src/capabilities.mjs');
}
