// Writes engine/v2/src/limits.mjs from spec/2.0/limits.json (9.8.1), so the engine, the checker and the packer use
// the spec's values and nothing else. Run it after set-limit.mjs; the fast tests fail while the file is stale.
// Usage: node engine/v2/tools/make-limits.mjs [--check]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '..', '..', '..');
export const target = path.join(repo, 'engine', 'v2', 'src', 'limits.mjs');

export function limitsModule() {
  const reg = JSON.parse(fs.readFileSync(path.join(repo, 'spec', '2.0', 'limits.json'), 'utf8'));
  const format = {}; const upTo = {}; const svg = {};
  for (const [id, e] of Object.entries(reg.limits)) { format[id] = e.value; if (e.upTo !== undefined) upTo[id] = e.upTo; if (e.svgLimit) svg[id] = JSON.stringify(e.svgLimit); }
  const obj = (o) => `{\n${Object.entries(o).map(([k, v]) => `  ${k}: ${v},`).join('\n')}\n}`;
  return `// Generated by engine/v2/tools/make-limits.mjs from spec/2.0/limits.json. Do not edit.
// The format limits (9.8, 9.8.1): FORMAT holds every value; UP_TO holds how far a capacity limit may be raised.

export const FORMAT = Object.freeze(${obj(format)});

export const UP_TO = Object.freeze(${obj(upTo)});

// The name each drawing limit has in the drawing rules (vocabularies.json svgLimits).
export const SVG_LIMIT = Object.freeze(${obj(svg)});

// The limits a package raises: for each raisable id, the largest value any of its experience documents asks for.
// Ids that cannot be raised are left out (the schemas refuse them in checked mode).
export function raisedLimits(docs) {
  const out = {};
  for (const d of docs) for (const [id, v] of Object.entries(d?.limits || {})) {
    if (!(id in UP_TO) || typeof v !== 'number' || v <= FORMAT[id] || v > UP_TO[id]) continue;
    out[id] = Math.max(out[id] ?? 0, v);
  }
  return out;
}

// The values that apply while playing: the format values, raised where the package asks.
export function activeLimits(raised = {}) { return Object.freeze({ ...FORMAT, ...raised }); }

// Admission (9.8.1): every raised limit must be allowed by the host profile at least as far as it is raised. A host
// without a profile allows only the format values. Returns the refusals: [{id, needs, allows}].
export function refusedLimits(raised, hostProfile) {
  const allows = hostProfile?.limits || {};
  return Object.entries(raised).filter(([id, v]) => (allows[id] ?? FORMAT[id]) < v).map(([id, v]) => ({ id, needs: v, allows: allows[id] ?? FORMAT[id] }));
}

export function refusalMessage(refused) {
  return refused.map(r => \`\${r.id} needs \${r.needs}, the host allows \${r.allows}\`).join('; ');
}
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = limitsModule();
  const old = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;
  if (process.argv.includes('--check')) { console.log(old === text ? 'limits.mjs is up to date' : 'limits.mjs is stale: run engine/v2/tools/make-limits.mjs'); process.exit(old === text ? 0 : 1); }
  if (old !== text) fs.writeFileSync(target, text);
  console.log(old === text ? 'limits.mjs is up to date' : 'wrote engine/v2/src/limits.mjs');
}
